"""
GOAL / PURPOSE:
    Step 07 (Final Gatekeeper) in the Krakow360 Python analytics pipeline.
    Automated Data Contract gatekeeper and schema integrity validator. Verifies
    that the final JSON deliverable files generated by the Python analytics pipeline
    (`krakow_districts_master.json`, `krakow_poi_locations.json`,
     `krakow_accessibility_profiles.json`, and `krakow_tourism_explorer.json`)
    strictly conform to the structural and type contracts expected by the .NET 9 EF Core DatabaseSeeder
    and the React 19 TypeScript frontend DTO interfaces.

WHAT THIS SCRIPT VALIDATES:
    1. Physical existence and UTF-8 JSON syntax integrity of all contract files in `data/contracts/`.
    2. Presence of exactly 18 administrative districts with IDs 1..18 without gaps or duplicates.
    3. Completeness of all 10 required domain aggregate sections for every district.
    4. Compliance of all 8 Quality of Life category scores (numeric floats within [0.0, 100.0]).
    5. Strict enum validation for B2B investment and deficit levels ('LOW', 'MEDIUM', 'HIGH').
    6. Geocoded civic Points of Interest (POIs) validation: allowed category and subCategory enums,
       valid district foreign keys (1..18), and WGS84 GPS coordinates within the Krakow metro bounding box.
    7. Civic Accessibility Profiles contract validation: 5 profile subscores + overall score within [0.0, 100.0],
       complete metrics for PRM parking, transit stops, public facilities, senior care, and recreation.
    8. Tourism Explorer contract validation: city visitor summary, curated attractions catalog with GPS bbox,
       overtourism alternative pairings, thematic itineraries with valid stops, and 18 district passports with transit times.

EXIT CODE:
    - Returns `0` ([OK]) when all contracts are 100% compliant with the architectural schema.
    - Returns `1` ([ERROR]) with an itemized diagnostic list of contract violations if any check fails.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Ensure script-level imports resolve config cleanly regardless of execution working directory
sys.path.append(str(Path(__file__).resolve().parent))

from config import (
    ALLOWED_POI_CATEGORIES,
    ALLOWED_POI_SUBCATEGORIES,
    ALLOWED_POTENTIAL_LEVELS,
    CONTRACTS_OUTPUT_DIR,
    KRAKOW_DISTRICTS,
    KRAKOW_MAX_LAT,
    KRAKOW_MAX_LNG,
    KRAKOW_MIN_LAT,
    KRAKOW_MIN_LNG,
    is_in_krakow_bbox,
)


def validate_districts_master(file_path: Path) -> list[str]:
    """
    Validates the primary district master contract file (`krakow_districts_master.json`).
    Asserts schema compliance across all 18 administrative districts, 10 nested domain sections,
    8 quality scores, and econometric classification enums.

    Args:
        file_path: Path to `data/contracts/krakow_districts_master.json`.

    Returns:
        List of formatted error strings describing any detected contract violations.
    """
    errors: list[str] = []

    # Step 1: Check physical file existence on disk before attempting to read
    if not file_path.exists():
        return [f"Missing master contract file: {file_path}"]

    # Step 2: Parse raw JSON stream and verify UTF-8 syntax integrity
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as exc:
        return [f"Invalid JSON syntax in {file_path}: {exc}"]

    # Step 3: Validate root contract payload structure ('metadata' and 'districts' collections)
    if "metadata" not in data or "districts" not in data:
        errors.append("Missing required root keys: contract must contain 'metadata' and 'districts'.")
        return errors

    # Step 4: Ensure exact cardinality matching the 18 official administrative districts of Krakow
    districts = data.get("districts", [])
    expected_district_count = len(KRAKOW_DISTRICTS)
    if len(districts) != expected_district_count:
        errors.append(f"Expected exactly {expected_district_count} districts, found {len(districts)}.")

    seen_ids: set[int] = set()

    # Step 5: Define the 10 mandatory domain aggregate sections expected by EF Core & TypeScript DTOs
    required_sections = [
        "scores",
        "demographics",
        "educationAndCare",
        "mobilityAndTransport",
        "greeneryAndSport",
        "cultureAndSociety",
        "forecastsAndB2B",
        "publicSafety",
        "housingMarket",
        "environmentalQuality",
    ]

    # Step 6: Define the 8 normalized Quality of Life category score keys [0.0 - 100.0]
    expected_score_keys = [
        "mobilityScore",
        "educationScore",
        "greeneryScore",
        "cultureAndSeniorScore",
        "environmentScore",
        "safetyScore",
        "housingAffordabilityScore",
        "demographicVitalityScore",
    ]

    # Step 7: Iterate over every district entity to assert schema and range conformance
    for idx, district in enumerate(districts):
        # Validate districtId is an integer strictly within the 1..18 administrative range
        d_id = district.get("districtId")
        if d_id is None or not isinstance(d_id, int) or not (1 <= d_id <= 18):
            errors.append(f"District at index {idx} has invalid districtId: {d_id} (must be int 1..18).")
        else:
            seen_ids.add(d_id)

        # Verify presence of all 10 required domain aggregate sections
        for sec in required_sections:
            if sec not in district:
                errors.append(f"District {d_id}: missing mandatory domain section '{sec}'.")

        # Verify that all 8 Quality of Life category scores are numeric floats within [0.0, 100.0]
        scores = district.get("scores", {})
        for score_key in expected_score_keys:
            val = scores.get(score_key)
            if val is None:
                errors.append(f"District {d_id}: missing quality score key '{score_key}'.")
            else:
                try:
                    num_val = float(val)
                    if not (0.0 <= num_val <= 100.0):
                        errors.append(
                            f"District {d_id}: '{score_key}' must be within [0.0, 100.0] (current value: {num_val})."
                        )
                except (ValueError, TypeError):
                    errors.append(f"District {d_id}: '{score_key}' value '{val}' is not a valid float.")

        # Verify that B2B potential and municipal deficit indicators strictly match allowed tri-state enums
        forecasts = district.get("forecastsAndB2B", {})
        for level_key in ["nurseryInvestmentPotentialB2B", "seniorInfrastructureDeficit", "greenSpaceDeficit"]:
            lvl = forecasts.get(level_key)
            if lvl not in ALLOWED_POTENTIAL_LEVELS:
                errors.append(
                    f"District {d_id}: '{level_key}' has invalid value '{lvl}'. Allowed enums: {ALLOWED_POTENTIAL_LEVELS}."
                )

    # Step 8: Assert that all district IDs from 1 to 18 are present without gaps or duplicates
    missing_ids = set(range(1, 19)) - seen_ids
    if missing_ids:
        errors.append(f"Missing district IDs in dataset: {sorted(missing_ids)}.")

    return errors


def validate_poi_locations(file_path: Path) -> list[str]:
    """
    Validates the civic Points of Interest contract file (`krakow_poi_locations.json`).
    Asserts schema compliance, allowed category/subcategory enums, district foreign key validity,
    and WGS84 GPS coordinate bounding box constraints.

    Args:
        file_path: Path to `data/contracts/krakow_poi_locations.json`.

    Returns:
        List of formatted error strings describing any detected POI contract violations.
    """
    errors: list[str] = []

    # Step 1: Check physical file existence on disk
    if not file_path.exists():
        return [f"Missing POI contract file: {file_path}"]

    # Step 2: Parse raw JSON stream and verify UTF-8 syntax integrity
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as exc:
        return [f"Invalid JSON syntax in {file_path}: {exc}"]

    # Step 3: Validate root 'pointsOfInterest' array collection
    pois = data.get("pointsOfInterest")
    if not isinstance(pois, list):
        return ["Missing or invalid 'pointsOfInterest' array in POI contract file."]

    if len(pois) == 0:
        errors.append("'pointsOfInterest' collection is empty. Expected catalog of civic facilities.")

    # Step 4: Iterate through all civic POIs and validate enum categorizations, district mapping, and GPS bounds
    for idx, poi in enumerate(pois):
        poi_id = poi.get("id", f"index_{idx}")

        # Validate primary category against AllowedPoiCategories enum in Domain
        cat = poi.get("category")
        if cat not in ALLOWED_POI_CATEGORIES:
            errors.append(f"POI '{poi_id}': invalid category='{cat}'. Allowed categories: {ALLOWED_POI_CATEGORIES}.")

        # Validate subcategory against AllowedPoiSubCategories enum in Domain
        sub_cat = poi.get("subCategory")
        if sub_cat not in ALLOWED_POI_SUBCATEGORIES:
            errors.append(
                f"POI '{poi_id}': invalid subCategory='{sub_cat}'. Allowed subcategories: {ALLOWED_POI_SUBCATEGORIES}."
            )

        # Validate district assignment (must belong to one of Krakow's 18 administrative units)
        did = poi.get("districtId")
        if did is None or not isinstance(did, int) or not (1 <= did <= 18):
            errors.append(f"POI '{poi_id}': invalid districtId={did}. Must be an integer 1..18.")

        # Validate geographic WGS84 coordinates against the official Krakow metropolitan bounding box
        lat, lng = poi.get("lat"), poi.get("lng")
        if lat is None or lng is None:
            errors.append(f"POI '{poi_id}': missing latitude or longitude.")
        else:
            try:
                lat_f, lng_f = float(lat), float(lng)
                if not is_in_krakow_bbox(lat_f, lng_f):
                    errors.append(
                        f"POI '{poi_id}': coordinates ({lat_f}, {lng_f}) lie outside the Krakow bounding box [{KRAKOW_MIN_LAT}..{KRAKOW_MAX_LAT}, {KRAKOW_MIN_LNG}..{KRAKOW_MAX_LNG}]."
                    )
            except (ValueError, TypeError):
                errors.append(f"POI '{poi_id}': coordinates ({lat}, {lng}) cannot be parsed as floats.")

    return errors


def validate_accessibility_profiles(file_path: Path) -> list[str]:
    """
    Validates the civic accessibility profiles contract file (`krakow_accessibility_profiles.json`).
    Asserts schema compliance across all 18 districts, 5 user profile subscores,
    transit, PRM parking, public facility audits, senior care, and recreation metrics.

    Args:
        file_path: Path to `data/contracts/krakow_accessibility_profiles.json`.

    Returns:
        List of formatted error strings describing any detected accessibility contract violations.
    """
    errors: list[str] = []

    if not file_path.exists():
        return [f"Missing accessibility profiles contract file: {file_path}"]

    try:
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as exc:
        return [f"Invalid JSON syntax in {file_path}: {exc}"]

    if "meta" not in data or "districts" not in data or "cityAverages" not in data:
        return ["Missing required root keys: contract must contain 'meta', 'cityAverages', and 'districts'."]

    # Validate city averages
    city_avg = data.get("cityAverages", {})
    if not isinstance(city_avg, dict) or "avgOverallScore" not in city_avg:
        errors.append("Invalid or missing 'cityAverages.avgOverallScore' in accessibility contract.")

    districts = data.get("districts", [])
    expected_count = len(KRAKOW_DISTRICTS)
    if len(districts) != expected_count:
        errors.append(f"Expected exactly {expected_count} districts in accessibility contract, found {len(districts)}.")

    expected_scores = [
        "overallScore",
        "mobilityScore",
        "visualScore",
        "hearingScore",
        "seniorScore",
        "familyStrollerScore",
    ]
    expected_metric_groups = ["prmParking", "transit", "publicFacilities", "seniorCare", "recreation"]

    seen_ids: set[int] = set()
    total_audited_facilities = 0

    for idx, d in enumerate(districts):
        did = d.get("districtId")
        if did is None or not isinstance(did, int) or not (1 <= did <= 18):
            errors.append(f"Accessibility district at index {idx} has invalid districtId: {did}")
        else:
            seen_ids.add(did)

        scores = d.get("scores", {})
        for s_key in expected_scores:
            val = scores.get(s_key)
            if val is None:
                errors.append(f"District {did}: missing accessibility score '{s_key}'")
            else:
                try:
                    num = float(val)
                    if not (0.0 <= num <= 100.0):
                        errors.append(f"District {did}: score '{s_key}' value {num} out of bounds [0.0, 100.0]")
                except (ValueError, TypeError):
                    errors.append(f"District {did}: score '{s_key}' is not a valid number")

        metrics = d.get("metrics", {})
        for m_key in expected_metric_groups:
            if m_key not in metrics:
                errors.append(f"District {did}: missing accessibility metrics group '{m_key}'")

        facilities = d.get("facilities", [])
        if isinstance(facilities, list):
            total_audited_facilities += len(facilities)

    missing_ids = set(range(1, 19)) - seen_ids
    if missing_ids:
        errors.append(f"Missing district IDs in accessibility dataset: {sorted(missing_ids)}")

    if total_audited_facilities < 15:
        errors.append(f"Expected at least 15 audited public facilities across Krakow, found {total_audited_facilities}")

    return errors


def validate_tourism_explorer(file_path: Path) -> list[str]:
    """
    Validates the Krakow Tourism Explorer contract file (`krakow_tourism_explorer.json`).
    Asserts schema compliance across city tourist summary statistics, attraction catalog,
    overtourism pairings, thematic itineraries, and 18 district passports.

    Args:
        file_path: Path to `data/contracts/krakow_tourism_explorer.json`.

    Returns:
        List of formatted error strings describing any detected tourism contract violations.
    """
    errors: list[str] = []

    if not file_path.exists():
        return [f"Missing tourism explorer contract file: {file_path}"]

    try:
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as exc:
        return [f"Invalid JSON syntax in {file_path}: {exc}"]

    # Required top-level sections
    required_root_keys = [
        "meta",
        "cityTourismSummary",
        "attractions",
        "overtourismAlternatives",
        "thematicItineraries",
        "districtPassports",
    ]
    for rk in required_root_keys:
        if rk not in data:
            errors.append(f"Tourism contract missing root key: '{rk}'")

    if errors:
        return errors

    # 1. City Tourism Summary validation
    summary = data.get("cityTourismSummary", {})
    annual_visitors = summary.get("annualVisitorsTotal", 0)
    if not isinstance(annual_visitors, (int, float)) or annual_visitors < 10_000_000:
        errors.append(f"cityTourismSummary.annualVisitorsTotal seems unrealistically low: {annual_visitors}")

    avg_stay = summary.get("averageStayDays", 0)
    if not isinstance(avg_stay, (int, float)) or avg_stay <= 0:
        errors.append(f"cityTourismSummary.averageStayDays must be a positive number: {avg_stay}")

    markets = summary.get("topInternationalMarkets", [])
    if not isinstance(markets, list) or len(markets) < 5:
        errors.append(f"Expected at least 5 topInternationalMarkets in cityTourismSummary, got {len(markets)}")

    # 2. Attractions validation
    attractions = data.get("attractions", [])
    if len(attractions) < 30:
        errors.append(f"Expected at least 30 curated attractions, found {len(attractions)}")

    allowed_crowd_levels = ["PEAK", "VERY_HIGH", "HIGH", "MODERATE", "LOW", "PEACEFUL"]

    attraction_ids: set[str] = set()
    for idx, att in enumerate(attractions):
        att_id = att.get("id")
        if not att_id or not isinstance(att_id, str):
            errors.append(f"Attraction at index {idx} has invalid id: {att_id}")
            continue

        if att_id in attraction_ids:
            errors.append(f"Duplicate attraction ID detected: '{att_id}'")
        attraction_ids.add(att_id)

        # District ID validation
        did = att.get("districtId")
        if did is None or not isinstance(did, int) or not (1 <= did <= 18):
            errors.append(f"Attraction '{att_id}': invalid districtId={did}")

        # GPS validation
        lat = att.get("lat")
        lng = att.get("lng")
        if lat is None or lng is None:
            errors.append(f"Attraction '{att_id}': missing lat/lng coordinates")
        else:
            try:
                lat_f, lng_f = float(lat), float(lng)
                if not is_in_krakow_bbox(lat_f, lng_f):
                    errors.append(f"Attraction '{att_id}': coordinates ({lat_f}, {lng_f}) outside Krakow bbox")
            except (ValueError, TypeError):
                errors.append(f"Attraction '{att_id}': coordinates cannot be parsed as floats")

        # Crowd level validation
        crowd = att.get("crowdLevel")
        if crowd not in allowed_crowd_levels:
            errors.append(f"Attraction '{att_id}': invalid crowdLevel '{crowd}' (allowed: {allowed_crowd_levels})")

    # 3. Overtourism Alternatives validation
    overtourism = data.get("overtourismAlternatives", [])
    if len(overtourism) < 5:
        errors.append(f"Expected at least 5 overtourism pairs, found {len(overtourism)}")

    for idx, pair in enumerate(overtourism):
        oc_id = pair.get("crowdedAttractionId")
        pc_id = pair.get("peacefulAttractionId")
        if oc_id not in attraction_ids:
            errors.append(f"Overtourism pair {idx}: crowdedAttractionId '{oc_id}' not found in attractions catalog")
        if pc_id not in attraction_ids:
            errors.append(f"Overtourism pair {idx}: peacefulAttractionId '{pc_id}' not found in attractions catalog")

    # 4. Thematic Itineraries validation
    itineraries = data.get("thematicItineraries", [])
    if len(itineraries) < 4:
        errors.append(f"Expected at least 4 thematic itineraries, found {len(itineraries)}")

    for itin in itineraries:
        itin_id = itin.get("id")
        stops = itin.get("stops", [])
        if not stops or len(stops) < 2:
            errors.append(f"Itinerary '{itin_id}': has fewer than 2 stops")
        for stop in stops:
            s_id = stop.get("attractionId") if isinstance(stop, dict) else stop
            if s_id not in attraction_ids:
                errors.append(f"Itinerary '{itin_id}': stop '{s_id}' not found in attractions catalog")

    # 5. District Passports validation (all 18 districts)
    passports = data.get("districtPassports", [])
    if len(passports) != 18:
        errors.append(f"Expected exactly 18 district passports, found {len(passports)}")

    seen_passport_dids: set[int] = set()
    for dp in passports:
        p_did = dp.get("districtId")
        if p_did is None or not isinstance(p_did, int) or not (1 <= p_did <= 18):
            errors.append(f"District passport has invalid districtId: {p_did}")
        else:
            seen_passport_dids.add(p_did)

        top_atts = dp.get("topAttractions", [])
        if not top_atts:
            errors.append(f"District passport {p_did}: topAttractions list is empty")
        for att in top_atts:
            att_id = att.get("id") if isinstance(att, dict) else att
            if att_id not in attraction_ids:
                errors.append(f"District passport {p_did}: top attraction '{att_id}' not in catalog")

        if "transitTimeFromStationMinutes" not in dp or "directTransitLines" not in dp:
            errors.append(f"District passport {p_did}: missing transit details from main station")

    missing_passports = set(range(1, 19)) - seen_passport_dids
    if missing_passports:
        errors.append(f"Missing district passports for IDs: {sorted(missing_passports)}")

    return errors


def main() -> int:
    """
    Main execution entry point for contract validation (Step 07 - Final Quality Gate).
    Runs validation routines sequentially across all four contract deliverables, prints an
    itemized diagnostic report, and returns exit code 0 on success or 1 on failure.
    """
    districts_file = CONTRACTS_OUTPUT_DIR / "krakow_districts_master.json"
    poi_file = CONTRACTS_OUTPUT_DIR / "krakow_poi_locations.json"
    access_file = CONTRACTS_OUTPUT_DIR / "krakow_accessibility_profiles.json"
    tourism_file = CONTRACTS_OUTPUT_DIR / "krakow_tourism_explorer.json"

    print("=== Krakow360 Data Contract Validation (Step 07 - Master, POI, Accessibility & Tourism) ===")

    d_errors = validate_districts_master(districts_file)
    p_errors = validate_poi_locations(poi_file)
    a_errors = validate_accessibility_profiles(access_file)
    t_errors = validate_tourism_explorer(tourism_file)

    all_errors = d_errors + p_errors + a_errors + t_errors
    if all_errors:
        print("\n[ERROR] Data contract validation failed:")
        for err in all_errors:
            print(f"  - {err}")
        print(f"\nTotal violations detected: {len(all_errors)}")
        return 1

    print("\n[OK] Validation passed:")
    print(f"  - Verified 18 districts in {districts_file.name}")
    print(f"  - Verified all 10 required domain sections per district")
    print(f"  - Verified all 8 Quality of Life category scores (0.0 - 100.0)")
    print(f"  - Verified Points of Interest in {poi_file.name}")
    print(f"  - Verified 18 accessibility profiles & subscores in {access_file.name}")
    print(f"  - Verified tourism summary, attractions, itineraries & 18 district passports in {tourism_file.name}")
    print("All JSON contract checks PASSED successfully.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""
GOAL / PURPOSE:
    Automated Data Contract gatekeeper and schema integrity validator. Verifies
    that the final JSON deliverable files generated by the Python analytics pipeline
    (`krakow_districts_master.json` and `krakow_poi_locations.json`) strictly conform
    to the structural and type contracts expected by the .NET 9 EF Core DatabaseSeeder
    and the React 19 TypeScript frontend DTO interfaces.

WHAT THIS SCRIPT VALIDATES:
    1. Physical existence and UTF-8 JSON syntax integrity of both contract files in `data/contracts/`.
    2. Presence of exactly 18 administrative districts with IDs 1..18 without gaps or duplicates.
    3. Completeness of all 10 required domain aggregate sections (`scores`, `demographics`,
       `educationAndCare`, `mobilityAndTransport`, `greeneryAndSport`, `cultureAndSociety`,
       `forecastsAndB2B`, `publicSafety`, `housingMarket`, `environmentalQuality`) for every district.
    4. Compliance of all 8 Quality of Life category scores (numeric floats within [0.0, 100.0]).
    5. Strict enum validation for B2B investment and deficit levels ('LOW', 'MEDIUM', 'HIGH').
    6. Geocoded civic Points of Interest (POIs) validation: allowed category and subCategory enums,
       valid district foreign keys (1..18), and WGS84 GPS coordinates within the Krakow metro bounding box.

EXIT CODE:
    - Returns `0` ([OK]) when both contracts are 100% compliant with the architectural schema.
    - Returns `1` ([ERROR]) with an itemized diagnostic list of contract violations if any check fails.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Ensure script-level imports resolve config cleanly regardless of execution working directory
sys.path.append(str(Path(__file__).resolve().parent))

from config import (
    ALLOWED_POI_CATEGORIES,
    ALLOWED_POI_SUBCATEGORIES,
    ALLOWED_POTENTIAL_LEVELS,
    CONTRACTS_OUTPUT_DIR,
    KRAKOW_DISTRICTS,
)


def validate_districts_master(file_path: Path) -> list[str]:
    """
    Validates the primary district master contract file (`krakow_districts_master.json`).
    Asserts schema compliance across all 18 administrative districts, 10 nested domain sections,
    8 quality scores, and econometric classification enums.

    Args:
        file_path: Path to `data/contracts/krakow_districts_master.json`.

    Returns:
        List of formatted error strings describing any detected contract violations.
    """
    errors: list[str] = []

    # Step 1: Check physical file existence on disk before attempting to read
    if not file_path.exists():
        return [f"Missing master contract file: {file_path}"]

    # Step 2: Parse raw JSON stream and verify UTF-8 syntax integrity
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as exc:
        return [f"Invalid JSON syntax in {file_path}: {exc}"]

    # Step 3: Validate root contract payload structure ('metadata' and 'districts' collections)
    if "metadata" not in data or "districts" not in data:
        errors.append("Missing required root keys: contract must contain 'metadata' and 'districts'.")
        return errors

    # Step 4: Ensure exact cardinality matching the 18 official administrative districts of Krakow
    districts = data.get("districts", [])
    expected_district_count = len(KRAKOW_DISTRICTS)
    if len(districts) != expected_district_count:
        errors.append(f"Expected exactly {expected_district_count} districts, found {len(districts)}.")

    seen_ids: set[int] = set()

    # Step 5: Define the 10 mandatory domain aggregate sections expected by EF Core & TypeScript DTOs
    required_sections = [
        "scores",
        "demographics",
        "educationAndCare",
        "mobilityAndTransport",
        "greeneryAndSport",
        "cultureAndSociety",
        "forecastsAndB2B",
        "publicSafety",
        "housingMarket",
        "environmentalQuality",
    ]

    # Step 6: Define the 8 normalized Quality of Life category score keys [0.0 - 100.0]
    expected_score_keys = [
        "mobilityScore",
        "educationScore",
        "greeneryScore",
        "cultureAndSeniorScore",
        "environmentScore",
        "safetyScore",
        "housingAffordabilityScore",
        "demographicVitalityScore",
    ]

    # Step 7: Iterate over every district entity to assert schema and range conformance
    for idx, district in enumerate(districts):
        # Validate districtId is an integer strictly within the 1..18 administrative range
        d_id = district.get("districtId")
        if d_id is None or not isinstance(d_id, int) or not (1 <= d_id <= 18):
            errors.append(f"District at index {idx} has invalid districtId: {d_id} (must be int 1..18).")
        else:
            seen_ids.add(d_id)

        # Verify presence of all 10 required domain aggregate sections
        for sec in required_sections:
            if sec not in district:
                errors.append(f"District {d_id}: missing mandatory domain section '{sec}'.")

        # Verify that all 8 Quality of Life category scores are numeric floats within [0.0, 100.0]
        scores = district.get("scores", {})
        for score_key in expected_score_keys:
            val = scores.get(score_key)
            if val is None:
                errors.append(f"District {d_id}: missing quality score key '{score_key}'.")
            else:
                try:
                    num_val = float(val)
                    if not (0.0 <= num_val <= 100.0):
                        errors.append(
                            f"District {d_id}: '{score_key}' must be within [0.0, 100.0] (current value: {num_val})."
                        )
                except (ValueError, TypeError):
                    errors.append(f"District {d_id}: '{score_key}' value '{val}' is not a valid float.")

        # Verify that B2B potential and municipal deficit indicators strictly match allowed tri-state enums
        forecasts = district.get("forecastsAndB2B", {})
        for level_key in ["nurseryInvestmentPotentialB2B", "seniorInfrastructureDeficit", "greenSpaceDeficit"]:
            lvl = forecasts.get(level_key)
            if lvl not in ALLOWED_POTENTIAL_LEVELS:
                errors.append(
                    f"District {d_id}: '{level_key}' has invalid value '{lvl}'. Allowed enums: {ALLOWED_POTENTIAL_LEVELS}."
                )

    # Step 8: Assert that all district IDs from 1 to 18 are present without gaps or duplicates
    missing_ids = set(range(1, 19)) - seen_ids
    if missing_ids:
        errors.append(f"Missing district IDs in dataset: {sorted(missing_ids)}.")

    return errors


def validate_poi_locations(file_path: Path) -> list[str]:
    """
    Validates the civic Points of Interest contract file (`krakow_poi_locations.json`).
    Asserts schema compliance, allowed category/subcategory enums, district foreign key validity,
    and WGS84 GPS coordinate bounding box constraints.

    Args:
        file_path: Path to `data/contracts/krakow_poi_locations.json`.

    Returns:
        List of formatted error strings describing any detected POI contract violations.
    """
    errors: list[str] = []

    # Step 1: Check physical file existence on disk
    if not file_path.exists():
        return [f"Missing POI contract file: {file_path}"]

    # Step 2: Parse raw JSON stream and verify UTF-8 syntax integrity
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as exc:
        return [f"Invalid JSON syntax in {file_path}: {exc}"]

    # Step 3: Validate root 'pointsOfInterest' array collection
    pois = data.get("pointsOfInterest")
    if not isinstance(pois, list):
        return ["Missing or invalid 'pointsOfInterest' array in POI contract file."]

    if len(pois) == 0:
        errors.append("'pointsOfInterest' collection is empty. Expected catalog of civic facilities.")

    # Step 4: Iterate through all civic POIs and validate enum categorizations, district mapping, and GPS bounds
    for idx, poi in enumerate(pois):
        poi_id = poi.get("id", f"index_{idx}")

        # Validate primary category against AllowedPoiCategories enum in Domain
        cat = poi.get("category")
        if cat not in ALLOWED_POI_CATEGORIES:
            errors.append(f"POI '{poi_id}': invalid category='{cat}'. Allowed categories: {ALLOWED_POI_CATEGORIES}.")

        # Validate subcategory against AllowedPoiSubCategories enum in Domain
        sub_cat = poi.get("subCategory")
        if sub_cat not in ALLOWED_POI_SUBCATEGORIES:
            errors.append(
                f"POI '{poi_id}': invalid subCategory='{sub_cat}'. Allowed subcategories: {ALLOWED_POI_SUBCATEGORIES}."
            )

        # Validate district assignment (must belong to one of Krakow's 18 administrative units)
        did = poi.get("districtId")
        if did is None or not isinstance(did, int) or not (1 <= did <= 18):
            errors.append(f"POI '{poi_id}': invalid districtId={did}. Must be an integer 1..18.")

        # Validate geographic WGS84 coordinates against the official Krakow metropolitan bounding box [49.9-50.2°N, 19.7-20.3°E]
        lat, lng = poi.get("lat"), poi.get("lng")
        if lat is None or lng is None:
            errors.append(f"POI '{poi_id}': missing latitude or longitude.")
        else:
            try:
                lat_f, lng_f = float(lat), float(lng)
                if not (49.9 <= lat_f <= 50.2) or not (19.7 <= lng_f <= 20.3):
                    errors.append(
                        f"POI '{poi_id}': coordinates ({lat_f}, {lng_f}) lie outside the Krakow bounding box."
                    )
            except (ValueError, TypeError):
                errors.append(f"POI '{poi_id}': coordinates ({lat}, {lng}) cannot be parsed as floats.")

    return errors


def main() -> int:
    """
    Main execution entry point for contract validation.
    Runs validation routines sequentially across both contract deliverables, prints an
    itemized diagnostic report, and returns exit code 0 on success or 1 on failure.
    """
    districts_file = CONTRACTS_OUTPUT_DIR / "krakow_districts_master.json"
    poi_file = CONTRACTS_OUTPUT_DIR / "krakow_poi_locations.json"

    print("=== Krakow360 Data Contract Validation (8 Pillars) ===")

    d_errors = validate_districts_master(districts_file)
    p_errors = validate_poi_locations(poi_file)

    all_errors = d_errors + p_errors
    if all_errors:
        print("\n[ERROR] Data contract validation failed:")
        for err in all_errors:
            print(f"  - {err}")
        print(f"\nTotal violations detected: {len(all_errors)}")
        return 1

    print("\n[OK] Validation passed:")
    print(f"  - Verified 18 districts in {districts_file.name}")
    print(f"  - Verified all 10 required domain sections per district")
    print(f"  - Verified all 8 Quality of Life category scores (0.0 - 100.0)")
    print(f"  - Verified Points of Interest in {poi_file.name}")
    print("All JSON contract checks PASSED successfully.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
